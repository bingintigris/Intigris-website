/* Writes one Astro page per language for every converted page in src/legacy/pages.json.
   Each page renders the old page's App to HTML at build time and hydrates it (client:load).
   Draft pages (ISA) go to src/pages/_drafts/ (not built; move out to switch on).
   Run: node scripts/gen-pages.mjs   (from site/) */
import fs from 'node:fs';
import path from 'node:path';

const SITE = path.resolve(import.meta.dirname, '..');
const meta = JSON.parse(fs.readFileSync(path.join(SITE, 'src/legacy/pages.json'), 'utf8'));
const DRAFTS = new Set(['ISA']);

/* Dutch titles where the English page title is generic */
const NL_TITLE = {};

for (const [page, m] of Object.entries(meta)) {
  for (const lang of ['en', 'nl']) {
    const rel = (m.route === '/' ? '/index' : m.route) + '.astro';
    const dir = DRAFTS.has(page) ? 'src/pages/_drafts' : 'src/pages';
    const file = path.join(SITE, dir, lang === 'nl' ? 'nl' : '', rel);
    fs.mkdirSync(path.dirname(file), { recursive: true });
    const up = path.relative(path.dirname(file), path.join(SITE, 'src')).split(path.sep).join('/');
    const app = page.replace(/-/g, '');
    const title = (lang === 'nl' && NL_TITLE[page]) || m.title;
    fs.writeFileSync(file, `---
/* ${lang.toUpperCase()} ${m.route} — generated by scripts/gen-pages.mjs from ${page}.html; safe to edit by hand */
import Layout from '${up}/layouts/Layout.astro';
import App from '${up}/legacy/apps/${app}.jsx';
import meta from '${up}/legacy/pages.json';
import { setLang } from '${up}/lib/i18n.js';
const lang = '${lang}';
setLang(lang);
const m = meta['${page}'];
---
<Layout lang={lang} title={${JSON.stringify(title)}} description={m.description} route={m.route} robots={m.robots} headExtra={m.head} bodyExtra={m.body}>
  <App client:load />
</Layout>
`);
  }
}
console.log('pages written');
